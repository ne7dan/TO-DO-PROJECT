export function pluralGoals(locale, count) {
  const dict = translations[locale] ?? translations.ru
  if (locale === 'en') {
    return count === 1 ? dict['todos.goalOne'] : dict['todos.goalMany']
  }
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11) return dict['todos.goalOne']
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) {
    return dict['todos.goalFew']
  }
  return dict['todos.goalMany']
}

export function interpolate(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] == null ? '' : String(vars[key]),
  )
}
